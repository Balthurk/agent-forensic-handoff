CREATE TABLE IF NOT EXISTS jobs(id TEXT PRIMARY KEY,source TEXT UNIQUE NOT NULL,offset INTEGER NOT NULL DEFAULT 0,valid_offset INTEGER NOT NULL DEFAULT 0,prefix TEXT NOT NULL,status TEXT NOT NULL,owner TEXT,lease_until INTEGER NOT NULL DEFAULT 0,current_case TEXT,error TEXT);

CREATE TABLE IF NOT EXISTS events(seq INTEGER PRIMARY KEY,job TEXT,at TEXT,status TEXT,detail TEXT);

CREATE TABLE IF NOT EXISTS revisions(job TEXT,hash TEXT,bytes INTEGER,case_id TEXT,status TEXT,PRIMARY KEY(job,hash));
