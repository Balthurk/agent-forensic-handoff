import {graphOperation} from './graph-publication.mjs';
import {causalOperation} from './causal.mjs';
import {intelligenceOperation} from './decision-intelligence.mjs';
import {retrospectiveOperation} from './retrospectives.mjs';
import fs from 'node:fs';
import {routingOperation} from './routing.mjs';
import {explorer} from './explorer.mjs';
import {identityOperation} from './identities.mjs';
import {retrievePackage,coverage,indexConversations,loadTaxonomy,SEMANTIC_TYPES,createProposal,listProposals,closeMemory} from './memory.mjs';
import {knowledgeOperation,extractKnowledge,reviewKnowledge} from './knowledge.mjs';
import {importDocument,documentStatus,reconcileDocuments} from './documents.mjs';
import {createCorpusPlan,runCorpusPlan,corpusPlanStatus,listCorpusPlans} from './corpus-plan.mjs';
import {collectiveOperation} from './collectives.mjs';
import {contextPage} from './context.mjs';
import {supportOperation} from './justifications.mjs';
const [command,file]=process.argv.slice(2);
try{
 const request=file?JSON.parse(fs.readFileSync(file,'utf8')):{};let result;
 reconcileDocuments();
 if(command==='document')result=await importDocument(request);
 else if(command==='collectives')result=await collectiveOperation(request.op,request);
 else if(command==='context-page')result=await contextPage(request);
 else if(command==='explorer')result=await explorer(request);
 else if(command==='routing')result=await routingOperation(request);
 else if(command==='graph-publication')result=await graphOperation(request.op,request);
 else if(command==='causal')result=await causalOperation(request.op,request);
 else if(command==='decision-intelligence')result=await intelligenceOperation(request.op,request);
 else if(command==='retrospectives')result=await retrospectiveOperation(request.op,request);
 else if(command==='identities')result=await identityOperation(request.op,request);
 else if(command==='supports')result=await supportOperation(request.op,request);
 else if(command==='documents')result=documentStatus();
 else if(command==='plan')result=await createCorpusPlan(request);
 else if(command==='plan-run')result=await runCorpusPlan(request);
 else if(command==='plan-status')result=request.id?corpusPlanStatus(request.id,request):listCorpusPlans();
 else if(command==='query')result=await retrievePackage(request.question,request.conversationIds,request.retrieval);
 else if(command==='coverage')result=await coverage();
 else if(command==='taxonomy')result={catalog:loadTaxonomy(),types:SEMANTIC_TYPES};
 else if(command==='index')result=await indexConversations(request.conversationIds);
 else if(command==='propose')result=await createProposal(request);
 else if(command==='proposals')result=await listProposals();
 else if(command==='extract')result=await extractKnowledge(request);
 else if(command==='review')result=await reviewKnowledge(request);
 else if(command==='knowledge')result=await knowledgeOperation(request.op,request.conversationIds,request.input||{});
 else throw new Error('Usage: node app/memory-cli.mjs query|index|propose|extract|review|knowledge|document|plan|plan-run|plan-status request.json; coverage|taxonomy|proposals|documents');
 process.stdout.write(JSON.stringify(result)+'\n');
}catch(error){console.error(error.message);process.exitCode=1;}finally{await closeMemory();}
